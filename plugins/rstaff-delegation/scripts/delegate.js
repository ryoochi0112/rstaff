#!/usr/bin/env node
// rstaff delegate.js — the model-agnostic delegation core (specs/delegation-layer.md §2).
// One shared primitive + thin per-CLI adapters. This is the ONE place that knows
// each external CLI's flags — the /consult advisor and the executor branch of the
// parallel-build loop both call through here instead of duplicating CLI wiring.
//
// argv building, model resolution, the sandbox guard, and output normalization are
// kept PURE (no I/O) so the wiring is unit-testable without live CLIs or auth.
// run()/spawnWithTimeout() do the actual process spawning + file I/O.
//
//   node delegate.js <adapter> <advise|review|resume|execute> [--model m] [--cwd dir]
//     [--sandbox mode] [--prompt-file f] [--prompt str] [--base branch]
//     [--search] [--thread-id id] [--output-schema f] [--timeout secs]
//     [--reasoning-effort level] [--attempt N] [--usage-log f] [--label text] [-o out.md]
//
// Timeout is Node-side (spawnSync({timeout})) — no dependency on a `timeout`
// binary (macOS ships none) — so a wedged external CLI can never wedge the
// dispatch loop.
'use strict';
const { spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const usageRoot = require('./locate.js').locate('rstaff-usage');
const usageLog = usageRoot ? require(path.join(usageRoot, 'scripts', 'usage.js')) : null;
const lib = require(path.join(__dirname, '..', 'hooks', 'lib.js'));

const DEFAULT_TIMEOUT_MS = 30 * 60 * 1000; // callers may override via opts.timeoutMs / --timeout
const GEMINI_DRAFT_TIMEOUT_MS = 180 * 1000;
const STDERR_TAIL_LEN = 800;

// Verified 2026-09-11: gemini-3.8-flash exists in the Vertex publisher catalog
// for a configured project in the global region (v1 countTokens returned 200;
// v1beta1 listing). The installed @google/gemini-cli 0.58.0 was also verified
// read-only with:
//   env CLOUDSDK_CONFIG="$HOME/.gcloud-config" GOOGLE_GENAI_USE_VERTEXAI=true \
//     GOOGLE_CLOUD_PROJECT=example-project GOOGLE_CLOUD_LOCATION=global \
//     gemini -m gemini-3.8-flash -p "<prompt>" --approval-mode plan --skip-trust -o text
// `--skip-trust` is required for headless use. `plan` alone is NOT a structural
// read-only guarantee — see GEMINI_DRAFT_EXCLUDED_TOOLS below for why draft mode
// also passes `--policy`. Keep the id explicit: if Vertex removes it, the CLI
// must fail visibly rather than silently choosing another model.
const GEMINI_DEFAULT_MODEL = 'gemini-3.8-flash';
const GEMINI_PROJECT_FIX = 'set RSTAFF_GEMINI_PROJECT (or export GOOGLE_CLOUD_PROJECT)';

// Verified 2026-09-11: `--approval-mode plan` alone is NOT a structural guarantee.
// The installed @google/gemini-cli 0.58.0's bundled policies/plan.toml allows
// `exit_plan_mode` non-interactively (`decision = "allow", priority = 70,
// modes = ["plan"], interactive = false`) — a headless `-p` run can call it and
// fall straight into an auto-approving execution mode, with cwd wherever this
// process was spawned. `--exclude-tools` does NOT exist as a top-level flag (only
// under `gemini mcp add`); confirmed via `gemini --help` and by running it, which
// errored `Unknown arguments: exclude-tools, excludeTools`. `--allowed-tools` is
// marked "[DEPRECATED: Use Policy Engine instead]" in --help, so the supported
// mechanism is `--policy <file>`: a TOML file passed this way loads at
// USER_POLICY_TIER (4.x), which outranks plan.toml's default tier (1.x) for any
// tool named here regardless of interactive/non-interactive. Live-verified: a
// prompt engineered to call exit_plan_mode then write a file succeeded with no
// --policy flag (wrote the file, wrote a plan under ~/.gemini/tmp/.../plans/) and
// was fully blocked (model reported the tools "not available", nothing written)
// with this policy file passed via --policy. Keep this list and the cwd-scratch
// spawn (see run()) as the two structural layers — `--approval-mode plan` is not
// trusted alone.
// The bundled plan.toml documents settings-based "Always Allow" at 4.95; priority
// 999 maps to user tier 4.999 above that band while remaining below admin tier 5.x.
const GEMINI_DRAFT_EXCLUDED_TOOLS = Object.freeze([
  'exit_plan_mode', 'enter_plan_mode', 'write_file', 'replace',
  'run_shell_command', 'invoke_agent', 'activate_skill', 'web_fetch',
]);

// PURE. The --policy file content for gemini draft mode (see comment above).
function buildGeminiDraftPolicyToml() {
  const names = GEMINI_DRAFT_EXCLUDED_TOOLS.map((t) => `"${t}"`).join(', ');
  return [
    '# Generated by rstaff delegate.js (gemini draft mode) — do not hand-edit.',
    '[[rule]]',
    `toolName = [${names}]`,
    'decision = "deny"',
    'priority = 999',
    'denyMessage = "rstaff draft mode: this tool is structurally disabled."',
    '',
  ].join('\n');
}

// The reasoning-effort levels the codex CLI knows (`-c model_reasoning_effort=…`).
// This lives here because delegate.js is the ONE place that knows each CLI's flags.
// Whether a *given model* accepts a given level is a second, narrower question the
// CLI's own model catalog answers — see route.checkTierSupport + /health.
const CODEX_EFFORTS = new Set(['minimal', 'low', 'medium', 'high', 'xhigh', 'max', 'ultra']);

// An unknown level used to be forwarded verbatim and die inside a dispatched
// worker at spawn time — the worst place to learn a route was mistyped. Fail at
// the call site instead, next to the sandbox guard and for the same reason.
function assertEffort(effort) {
  if (effort && !CODEX_EFFORTS.has(effort)) {
    throw new Error(`delegate: unknown codex reasoning effort "${effort}" (known: ${[...CODEX_EFFORTS].join(', ')})`);
  }
}

function addCodexOptions(args, o) {
  assertEffort(o.reasoningEffort);
  if (o.model) args.push('-m', o.model);
  if (o.reasoningEffort) args.push('-c', `model_reasoning_effort="${o.reasoningEffort}"`);
  if (o.outputSchema) args.push('--output-schema', o.outputSchema);
  if (o.lastMessageFile) args.push('-o', o.lastMessageFile);
}

// --- adapter registry ---------------------------------------------------------
// The ONE place that knows each CLI's flags. Adding gemini/oss later is just
// another entry with a `bin` + `modes.{advise,review,execute}` argv builder.
const ADAPTERS = {
  codex: {
    bin: 'codex',
    modes: {
      // exec -s read-only -C <cwd> --skip-git-repo-check [-m <model>] [--output-schema <s>] [-o <f>] [<prompt>]
      advise(o) {
        const args = ['exec', '-s', 'read-only', '-C', o.cwd, '--skip-git-repo-check'];
        addCodexOptions(args, o);
        args.push('--json');
        if (o.prompt) args.push(o.prompt);
        return args;
      },
      // exec review --base <base> [-o <f>] --json [<prompt>]
      review(o) {
        const args = ['exec', 'review', '--base', o.base];
        addCodexOptions(args, o);
        args.push('--json');
        if (o.prompt) args.push(o.prompt);
        return args;
      },
      // exec resume has no -s or -C: force read-only via config; run() sets spawn cwd.
      resume(o) {
        if (typeof o.threadId !== 'string' || !o.threadId.trim()) {
          throw new Error('delegate: codex resume requires a non-empty threadId');
        }
        if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(o.threadId)) {
          // codex resume also accepts thread NAMES; a UUID-only id can't select an unrelated named session.
          throw new Error('delegate: codex resume requires a threadId that is a session UUID');
        }
        const args = ['exec', 'resume', o.threadId, '--skip-git-repo-check', '-c', 'sandbox_mode="read-only"'];
        addCodexOptions(args, o);
        args.push('--json');
        if (o.prompt) args.push(o.prompt);
        return args;
      },
      // exec -s workspace-write -C <cwd> --skip-git-repo-check [-m <model>] [-o <f>] [<prompt>]
      // --skip-git-repo-check: codex refuses to run in a non-git/untrusted dir without
      // it. Confinement stays with the explicit -C <cwd> + the sandbox above.
      execute(o) {
        const args = ['exec', '-s', 'workspace-write', '-C', o.cwd, '--skip-git-repo-check'];
        addCodexOptions(args, o);
        args.push('--json');
        if (o.prompt) args.push(o.prompt);
        return args;
      },
    },
  },
  gemini: {
    bin: 'gemini',
    modes: {
      // `--policy <file>` (o.policyFile, written by run() — see GEMINI_DRAFT_EXCLUDED_TOOLS)
      // is the structural block on exit_plan_mode et al.; plan mode alone is not enough.
      draft(o) {
        const args = ['-m', o.model, '-p', o.prompt, '--approval-mode', 'plan', '--skip-trust'];
        if (o.policyFile) args.push('--policy', o.policyFile);
        args.push('-o', 'text');
        return args;
      },
    },
  },
};

// --- sandbox guard -------------------------------------------------------------
// Refuse `danger-full-access` unless the operator explicitly opts in via env.
// codex advise/review/resume always run read-only, codex execute always runs
// workspace-write regardless of this — this guard is defense-in-depth against
// any caller (present or future adapter) ever requesting danger-full-access.
// Never emit `--dangerously-bypass-*`.
function assertSandbox(sandbox) {
  if (sandbox === 'danger-full-access' && process.env.RSTAFF_DELEGATE_ALLOW_DANGER !== '1') {
    throw new Error('delegate: sandbox "danger-full-access" is refused — set RSTAFF_DELEGATE_ALLOW_DANGER=1 to explicitly override (never --dangerously-bypass-*)');
  }
}

// --- pure argv builder -----------------------------------------------------------
function buildArgv(opts) {
  opts = opts || {};
  assertSandbox(opts.sandbox);
  const entry = ADAPTERS[opts.adapter];
  if (!entry) throw new Error(`delegate: unknown adapter "${opts.adapter}" (known: ${Object.keys(ADAPTERS).join(', ')})`);
  const build = entry.modes[opts.mode];
  if (!build) throw new Error(`delegate: unknown mode "${opts.mode}" for adapter "${opts.adapter}" (known: ${Object.keys(entry.modes).join(', ')})`);
  if (opts.adapter === 'codex' && opts.search && opts.mode === 'execute') {
    throw new Error('delegate: codex --search is not allowed in execute mode');
  }
  const args = build(opts);
  if (opts.adapter === 'codex' && opts.search) args.unshift('--search');
  return { bin: entry.bin, args };
}

// --- pure model resolution -------------------------------------------------------
// codex: passthrough or null (null = omit -m; codex's own ~/.codex/config.toml
// default, e.g. gpt-5.6-sol, applies). A future adapter that cannot infer its own
// default belongs here, erroring with its discovery command rather than a
// hardcoded model id.
function resolveModel(adapter, alias) {
  if (adapter === 'gemini') return alias || GEMINI_DEFAULT_MODEL;
  return alias || null;
}

// PURE. Programmatic millisecond overrides take precedence over the CLI's
// second-based override; Gemini drafts otherwise use their shorter contract.
function resolveTimeoutMs({ adapter, mode, timeoutMs, timeoutSec }) {
  if (timeoutMs !== undefined && timeoutMs !== null) return timeoutMs;
  if (timeoutSec !== undefined && timeoutSec !== null) return timeoutSec * 1000;
  return adapter === 'gemini' && mode === 'draft'
    ? GEMINI_DRAFT_TIMEOUT_MS
    : DEFAULT_TIMEOUT_MS;
}

// --- pure output normalizer --------------------------------------------------------
function tail(s, n) {
  const str = typeof s === 'string' ? s : '';
  return str.length > n ? str.slice(-n) : str;
}
function looksLikeJSON(s) {
  if (typeof s !== 'string') return false;
  const t = s.trim();
  return t.length > 0 && (t[0] === '{' || t[0] === '[');
}
// Always the same shape, whatever the inputs — callers reconcile on `ok`/`text`
// without needing to know which adapter ran.
function shape(o) {
  return {
    ok: !!o.ok,
    text: typeof o.text === 'string' ? o.text : '',
    structured: o.structured === undefined ? null : o.structured,
    timedOut: !!o.timedOut,
    exitCode: o.exitCode === undefined ? null : o.exitCode,
    stderrTail: typeof o.stderrTail === 'string' ? o.stderrTail : '',
    sessionId: typeof o.sessionId === 'string' ? o.sessionId : null,
    usage: o.usage && typeof o.usage === 'object' ? o.usage : null,
  };
}

function normalizeUsage(u) {
  if (!u || typeof u !== 'object') return null;
  const n = (camel, snake) => {
    const v = u[camel] !== undefined ? u[camel] : u[snake];
    return Number.isFinite(Number(v)) ? Number(v) : 0;
  };
  const usage = {
    inputTokens: n('inputTokens', 'input_tokens'),
    cachedInputTokens: n('cachedInputTokens', 'cached_input_tokens'),
    cacheWriteInputTokens: n('cacheWriteInputTokens', 'cache_write_input_tokens'),
    outputTokens: n('outputTokens', 'output_tokens'),
    reasoningOutputTokens: n('reasoningOutputTokens', 'reasoning_output_tokens'),
  };
  usage.totalTokens = usage.inputTokens + usage.outputTokens;
  return Object.values(usage).every((v) => v === 0) ? null : usage;
}

function addUsage(a, b) {
  if (!a) return b;
  if (!b) return a;
  const out = {};
  for (const key of ['inputTokens', 'cachedInputTokens', 'cacheWriteInputTokens', 'outputTokens', 'reasoningOutputTokens']) {
    out[key] = (Number(a[key]) || 0) + (Number(b[key]) || 0);
  }
  out.totalTokens = out.inputTokens + out.outputTokens;
  return out;
}

// `codex exec --json` emits JSONL. Keep the full transcript out of callers'
// context: extract only the thread id, final agent message, and turn usage.
function parseCodexJSONL(raw) {
  const out = { sessionId: null, usage: null, text: '', sawEvent: false };
  if (!raw || typeof raw !== 'string') return out;
  for (const line of raw.split(/\r?\n/)) {
    if (!line.trim()) continue;
    let ev;
    try { ev = JSON.parse(line); } catch (_) { continue; }
    out.sawEvent = true;
    if (ev.type === 'thread.started' && typeof ev.thread_id === 'string') out.sessionId = ev.thread_id;
    if (ev.type === 'turn.completed') out.usage = addUsage(out.usage, normalizeUsage(ev.usage));
    if (ev.type === 'item.completed' && ev.item && ev.item.type === 'agent_message' && typeof ev.item.text === 'string') {
      out.text = ev.item.text;
    }
  }
  return out;
}

// PURE. Rollout telemetry is stored separately from codex exec's stdout JSONL.
function parseCodexRollout(text, opts = {}) {
  const out = { quota: null, modelCalls: null, peakContext: null, contextWindow: null, effort: null };
  if (typeof text !== 'string') return out;
  const windows = { primary: null, secondary: null };
  for (const line of text.split(/\r?\n/)) {
    let event;
    try { event = JSON.parse(line); } catch (_) { continue; }
    if (!event || typeof event !== 'object' || !event.payload || typeof event.payload !== 'object') continue;
    if (Number.isFinite(opts.since)) {
      const timestamp = typeof event.timestamp === 'string' ? Date.parse(event.timestamp) : NaN;
      if (!Number.isFinite(timestamp) || timestamp < opts.since) continue;
    }
    const payload = event.payload;
    if (event.type === 'turn_context') {
      const effort = payload.effort ?? payload.reasoning_effort;
      out.effort = typeof effort === 'string' ? effort : null;
    }
    if (event.type !== 'event_msg' || payload.type !== 'token_count') continue;
    const info = payload.info;
    if (!info || typeof info !== 'object' || Array.isArray(info)) continue;
    out.modelCalls = (out.modelCalls || 0) + 1;
    const input = info.last_token_usage?.input_tokens;
    if (Number.isFinite(input)) out.peakContext = Math.max(out.peakContext ?? input, input);
    out.contextWindow = Number.isFinite(info.model_context_window) ? info.model_context_window : null;
    for (const name of ['primary', 'secondary']) {
      const window = payload.rate_limits?.[name];
      if (!window || !Number.isFinite(window.used_percent)) continue;
      const resetsAt = Number.isFinite(window.resets_at) ? window.resets_at : null;
      const windowMinutes = Number.isFinite(window.window_minutes) ? window.window_minutes : null;
      const previous = windows[name];
      if (!previous) {
        windows[name] = { start: window.used_percent, end: window.used_percent, windowMinutes, resetsAt, reset: false };
      } else {
        previous.reset = previous.reset || previous.resetsAt !== resetsAt || window.used_percent < previous.end;
        previous.end = window.used_percent;
        previous.windowMinutes = windowMinutes;
        previous.resetsAt = resetsAt;
      }
    }
  }
  out.quota = windows.primary || windows.secondary ? windows : null;
  return out;
}

// Read-only lookup: inspect only sessions' three date-directory levels.
function findCodexRollout(home, threadId) {
  if (typeof threadId !== 'string' || !threadId) return null;
  const entries = (dir) => {
    try { return fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return []; }
  };
  let directories = [path.resolve(home, 'sessions')];
  for (let depth = 0; depth < 3; depth++) {
    directories = directories.flatMap((dir) => entries(dir)
      .filter((entry) => entry.isDirectory()).map((entry) => path.join(dir, entry.name)));
  }
  for (const dir of directories) {
    const file = entries(dir).find((entry) => entry.isFile()
      && entry.name.startsWith('rollout-') && entry.name.endsWith(`-${threadId}.jsonl`));
    if (file) return path.join(dir, file.name);
  }
  return null;
}

function normalize(opts) {
  opts = opts || {};
  const { adapter, stdout, lastMessageText, exitCode, timedOut, stderr } = opts;
  const stderrTail = tail(stderr, STDERR_TAIL_LEN);

  if (timedOut) return shape({ ok: false, timedOut: true, text: '', exitCode, stderrTail });

  // codex (and future adapters default to the same last-message-first handling).
  const events = parseCodexJSONL(stdout);
  const text = lastMessageText || events.text || (events.sawEvent ? '' : stdout || '');
  if (exitCode !== 0) {
    return shape({
      ok: false, text, exitCode, stderrTail,
      sessionId: events.sessionId, usage: events.usage,
    });
  }
  if (adapter === 'gemini' && !text.trim()) {
    return shape({ ok: false, text: '', exitCode, stderrTail, sessionId: events.sessionId, usage: events.usage });
  }
  if (looksLikeJSON(text)) {
    try {
      return shape({
        ok: true, text, structured: JSON.parse(text), exitCode, stderrTail,
        sessionId: events.sessionId, usage: events.usage,
      });
    } catch (_) { /* schema ignored / malformed — fall back to text, never throw */ }
  }
  return shape({
    ok: true, text, exitCode, stderrTail,
    sessionId: events.sessionId, usage: events.usage,
  });
}

function appendUsageLog(logPath, record) {
  return usageLog ? usageLog.appendRecord(logPath, record) : null;
}

// --- availability probe ----------------------------------------------------------
function binExists(bin, env = process.env) {
  try {
    const r = spawnSync('sh', ['-c', 'command -v -- "$1"', 'sh', bin], { encoding: 'utf8', env });
    return r.status === 0;
  } catch (_) { return false; }
}
function hasGeminiProject(env = process.env) {
  return [env.RSTAFF_GEMINI_PROJECT, env.GOOGLE_CLOUD_PROJECT]
    .some((project) => typeof project === 'string' && project.trim().length > 0);
}
function isAvailable(adapter, env = process.env) {
  const entry = ADAPTERS[adapter];
  if (adapter === 'gemini' && !hasGeminiProject(env)) return false;
  return entry ? binExists(entry.bin, env) : false;
}

// --- timeout-wrapped spawn (the anti-hang mechanism) ------------------------------
// Node-side timeout only (spawnSync({timeout})) — portable, and the only thing
// standing between a hung external CLI and a wedged /dispatch loop.
function spawnWithTimeout({ bin, args, cwd, env, timeoutMs }) {
  const r = spawnSync(bin, args || [], {
    encoding: 'utf8',
    cwd: cwd || process.cwd(),
    env: env || process.env,
    timeout: timeoutMs,
  });
  const timedOut = r.signal === 'SIGTERM' || !!(r.error && r.error.code === 'ETIMEDOUT');
  return {
    stdout: r.stdout || '',
    stderr: r.stderr || '',
    exitCode: typeof r.status === 'number' ? r.status : null,
    timedOut,
  };
}

// --- the dedicated CODEX_HOME -----------------------------------------------
// codex accepts a models_cache.json only when its `client_version` is EXACTLY the
// running CLI's — measured with RUST_LOG, and an ordering compare or
// a schema check is not a faithful stand-in for it. One CODEX_HOME shared by two
// codex builds is therefore a race the newest writer always wins. Measured
// 2026-09-10: the PATH shim rstaff spawns was 0.153.2, the app's bundled app-server
// 0.153.4, and their shared `~/.codex/models_cache.json` was stamped 0.153.4 — so
// every codex route rstaff dispatched logged `cache version mismatch` and ran on
// built-in metadata, while route.checkTierSupport and /health certified the catalog
// in that very file. One path, two oracles that never agreed.
//
// So rstaff's codex runs get their OWN home. Everything the operator AUTHORED is
// symlinked back to their real home, so behaviour is otherwise identical; only what
// codex WRITES — models_cache.json above all — is private. route.codexHome() and
// /health resolve through here too, which is what makes their verdicts statements
// about the binary rstaff actually spawns.
//
// Opt out with RSTAFF_CODEX_HOME=<the shared home>: the seeder detects the identity
// case and touches nothing.
const CODEX_HOME_SEEDS = ['config.toml', 'auth.json', 'AGENTS.md'];
// Seeding REMOVES whatever sits on a seed name, and RSTAFF_CODEX_HOME can aim that
// at any path. So a home is rstaff's to write in only if rstaff can prove it owns
// it: this marker, dropped when the directory is created.
const CODEX_HOME_MARKER = '.rstaff-codex-home';

// The operator's own codex home — the source of truth for auth + config.
function sharedCodexHome() {
  return (process.env.CODEX_HOME || '').trim() || path.join(os.homedir(), '.codex');
}

// The home rstaff's codex runs use: gitignored control-repo working state, next to
// every other derived thing the loop keeps.
function codexHome() {
  const pinned = (process.env.RSTAFF_CODEX_HOME || '').trim();
  if (pinned) return path.resolve(pinned);
  return path.join(lib.resolveHome(process.cwd()), 'var', 'codex-home');
}

// When codex refreshes a token it rewrites auth.json via temp+rename, and rename()
// over a symlink path REPLACES the symlink with a real file — the source's copy is
// left untouched. So a diverged auth.json in the dedicated home may hold the only
// live credential, and the refresh token that minted it is single-use: discard it
// and the source's older copy can no longer be refreshed either. `last_refresh` is
// the stamp codex writes beside the token; null means we cannot date this side.
function authRefreshedAt(file) {
  try {
    const at = Date.parse(JSON.parse(fs.readFileSync(file, 'utf8')).last_refresh);
    return Number.isNaN(at) ? null : at;
  } catch (_) { return null; }              // absent, unreadable, not JSON, no stamp
}

// Copy `src` over `dest` the way codex writes a credential: a temp file in dest's
// OWN directory, then rename. A crash can then leave the old file or the new one,
// never a truncated one — and same-directory keeps rename() off an EXDEV path.
function replaceFile(src, dest) {
  const tmp = `${dest}.rstaff-${process.pid}-${Date.now()}`;
  fs.copyFileSync(src, tmp);
  fs.chmodSync(tmp, 0o600);                 // it is a secret wherever it lands
  fs.renameSync(tmp, dest);
}

// Identity has to be decided on the REAL path. A string compare is not identity:
// /tmp and /private/tmp are one directory on macOS, and a home that is a symlink to
// the source compares unequal while resolving into the very files the seeder would
// remove — and then re-link at themselves, leaving the operator a ring of dangling
// links where their credential used to be.
function samePath(a, b) {
  const real = (p) => { try { return fs.realpathSync(p); } catch (_) { return path.resolve(p); } };
  return real(a) === real(b);
}

// Establish that `home` is rstaff's before anything in it is removed. A directory
// rstaff just created is; so is one carrying the marker. A pre-existing, unmarked
// one is adopted only when it holds nothing we could destroy — every seed name
// either absent or already a link into `source`, which is what an upgrade meets on
// a home seeded before the marker existed. Anything else throws and names the path,
// because the alternative is deleting an operator's config without telling them.
function claimCodexHome(home, source, created) {
  const marker = path.join(home, CODEX_HOME_MARKER);
  if (!created && !fs.existsSync(marker)) {
    for (const name of CODEX_HOME_SEEDS) {
      const dest = path.join(home, name);
      let st = null;
      try { st = fs.lstatSync(dest); } catch (_) { continue; }   // absent: nothing at stake
      if (st.isSymbolicLink() && fs.readlinkSync(dest) === path.join(source, name)) continue;
      throw new Error(`refusing to seed ${home}: it already holds ${name}, and no `
        + `${CODEX_HOME_MARKER} marks it as rstaff's — seeding would DELETE that file. `
        + `Point RSTAFF_CODEX_HOME at a directory rstaff owns or an empty one, or, if this `
        + `directory really is rstaff's, adopt it with: touch ${marker}`);
    }
  }
  fs.writeFileSync(marker, "rstaff's dedicated CODEX_HOME. Delete this whole "
    + 'directory to reset it; the next codex route re-seeds it from the operator home.\n');
}

// Point `dest` at `src`. /dispatch runs up to three feature-runners into one home,
// each removing a seed name and re-linking it, so a peer's symlink can land between
// our rmSync and this call. Losing that race produces the outcome we wanted anyway,
// so it is not an error — but only when what landed IS our link. Anything else is a
// real collision, and swallowing it would run codex against the wrong credential.
function linkSeed(src, dest) {
  try {
    fs.symlinkSync(src, dest);
  } catch (e) {
    if (e.code !== 'EEXIST') throw e;
    let link = null;
    try { link = fs.readlinkSync(dest); } catch (_) { /* a real file, not a link */ }
    if (link !== src) throw e;
  }
}

// Prepare `home` so a codex spawned against it behaves like the operator's own.
// Throws rather than falling back, for the same reason assertEffort does: an unseeded
// home means an unauthenticated run, and learning that inside a dispatched worker
// costs a whole task attempt.
function ensureCodexHome(home = codexHome(), source = sharedCodexHome()) {
  // mkdir FIRST: the identity guard below reads the real path, and a home that does
  // not exist yet has none. `mkdirSync` returns the first directory it created, or
  // undefined when the path was already there — the only honest signal for whether
  // this directory is ours or something the operator already had.
  const created = fs.mkdirSync(home, { recursive: true }) !== undefined;
  if (samePath(home, source)) return home;  // the opt-out: touch nothing, mark nothing
  claimCodexHome(home, source, created);
  for (const name of CODEX_HOME_SEEDS) {
    const src = path.join(source, name);
    if (!fs.existsSync(src)) continue;      // nothing to point at
    const dest = path.join(home, name);
    let link = null;
    try { link = fs.readlinkSync(dest); } catch (_) { /* absent, or a real file */ }
    if (link === src) continue;
    // Anything else is ours to replace: a link to a home the operator has since
    // moved, or the real file codex leaves behind on a token refresh. But that file
    // may be NEWER than the source, so re-linking it away is credential loss, not
    // cleanup. The newer `last_refresh` wins and is copied back before we re-link.
    //
    // This is the ONE write into the source home, and it is deliberately narrow:
    // auth.json only, both sides dateable, ours strictly newer. config.toml and
    // AGENTS.md are operator-AUTHORED — codex never rewrites them, so a diverged
    // copy there is always the stale side — and an undateable divergence is a
    // guess, which is exactly what must never be aimed at the operator's home.
    if (name === 'auth.json' && link === null) {
      const ours = authRefreshedAt(dest);
      const theirs = authRefreshedAt(src);
      if (ours !== null && theirs !== null && ours > theirs) replaceFile(dest, src);
    }
    // `recursive` because a seed name can diverge into a DIRECTORY, and `force`
    // because a peer may have removed it already; every other error is real and
    // must reach the caller rather than be swallowed into a confusing EEXIST.
    fs.rmSync(dest, { force: true, recursive: true });
    linkSeed(src, dest);
  }
  return home;
}

// PURE. The one place the dedicated home enters a child's environment.
function buildEnv({ adapter, env, codexHome: home }) {
  const base = env || process.env;
  if (adapter === 'gemini') {
    const project = [base.RSTAFF_GEMINI_PROJECT, base.GOOGLE_CLOUD_PROJECT]
      .find((value) => typeof value === 'string' && value.trim().length > 0);
    if (!project) throw new Error(`delegate: gemini unavailable — FIX: ${GEMINI_PROJECT_FIX}`);
    const child = {
      ...base,
      GOOGLE_GENAI_USE_VERTEXAI: 'true',
      GOOGLE_CLOUD_PROJECT: project,
      GOOGLE_CLOUD_LOCATION: base.RSTAFF_GEMINI_LOCATION || 'global',
    };
    delete child.GEMINI_API_KEY;
    delete child.GOOGLE_API_KEY;
    return child;
  }
  if (adapter !== 'codex' || !home) return base;
  return { ...base, CODEX_HOME: home };
}

// --- integration path: resolveModel -> buildArgv -> spawn -> normalize -----------
// The only function here that does I/O. Any provider credential in the parent
// shell reaches the child via plain env inheritance only — it is never read
// into a prompt, a file, or a log line.
function run(opts) {
  opts = opts || {};
  const { adapter, mode } = opts;
  const model = resolveModel(adapter, opts.model);
  const cwd = opts.cwd || process.cwd();
  const sandbox = opts.sandbox || (mode === 'execute' ? 'workspace-write' : 'read-only');
  const prompt = opts.promptFile ? fs.readFileSync(opts.promptFile, 'utf8') : (opts.prompt || '');

  // codex's `-o <file>` last-message capture. A future adapter without an
  // equivalent falls through to normalize() reading its stdout directly.
  const lastMessageFile = adapter === 'codex'
    ? path.join(os.tmpdir(), `rstaff-delegate-${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2)}.txt`)
    : null;

  // gemini draft NEVER runs with cwd = the caller's cwd (see GEMINI_DRAFT_EXCLUDED_TOOLS):
  // a fresh, empty scratch dir means the product repo's .gemini/settings.json, GEMINI.md,
  // hooks, and workspace policies are never discovered or loaded. The --policy file (the
  // structural tool block) lives alongside it and is removed with it.
  const isGeminiDraft = adapter === 'gemini' && mode === 'draft';
  let geminiScratchDir = null;
  let spawned;
  let timeoutMs;
  let childCodexHome;
  let startedAt;
  try {
    if (isGeminiDraft) {
      geminiScratchDir = fs.mkdtempSync(path.join(os.tmpdir(), 'rstaff-gemini-draft-'));
    }
    const policyFile = geminiScratchDir ? path.join(geminiScratchDir, 'policy.toml') : null;
    if (policyFile) fs.writeFileSync(policyFile, buildGeminiDraftPolicyToml());
    const spawnCwd = geminiScratchDir || cwd;

    const { bin, args } = buildArgv({
      adapter, mode, model, cwd, sandbox, prompt,
      base: opts.base, outputSchema: opts.outputSchema,
      lastMessageFile, reasoningEffort: opts.reasoningEffort, policyFile,
      search: opts.search, threadId: opts.threadId,
    });

    timeoutMs = resolveTimeoutMs({ adapter, mode, timeoutMs: opts.timeoutMs, timeoutSec: opts.timeoutSec });
    childCodexHome = adapter === 'codex' ? ensureCodexHome() : null;
    const env = buildEnv({
      adapter,
      env: opts.env || process.env,
      codexHome: childCodexHome,
    });
    startedAt = Date.now();
    spawned = spawnWithTimeout({ bin, args, cwd: spawnCwd, env, timeoutMs });
  } finally {
    if (geminiScratchDir) {
      const scratchBasename = path.basename(geminiScratchDir);
      if (scratchBasename.startsWith('rstaff-gemini-draft-')) {
        const geminiProjectDir = path.join(os.homedir(), '.gemini', 'tmp', scratchBasename);
        try { fs.rmSync(geminiProjectDir, { force: true, recursive: true }); } catch (_) { /* best-effort cleanup */ }
      }
      try { fs.rmSync(geminiScratchDir, { force: true, recursive: true }); } catch (_) { /* best-effort cleanup */ }
    }
  }

  let lastMessageText = '';
  if (lastMessageFile) {
    try { lastMessageText = fs.readFileSync(lastMessageFile, 'utf8'); } catch (_) { /* not written (timeout/crash) */ }
    try { fs.unlinkSync(lastMessageFile); } catch (_) {}
  }

  const normalized = normalize({
    adapter, mode,
    stdout: spawned.stdout,
    lastMessageText,
    exitCode: spawned.exitCode,
    timedOut: spawned.timedOut,
    stderr: spawned.stderr,
  });
  let rollout = null;
  if (adapter === 'codex' && normalized.sessionId) {
    try {
      const file = findCodexRollout(childCodexHome, normalized.sessionId);
      if (file) rollout = parseCodexRollout(fs.readFileSync(file, 'utf8'), { since: startedAt });
    } catch (_) { /* telemetry must never change the run */ }
  }
  return { ...normalized, timeoutMs, rollout };
}

// --- CLI (node delegate.js <adapter> <advise|review|resume|execute> [flags]) -----
function parseCliArgs(argv) {
  const [adapter, mode, ...rest] = argv;
  const opts = { adapter, mode };
  const FLAGS = {
    '--model': 'model', '--cwd': 'cwd', '--sandbox': 'sandbox',
    // `--brief` is the doc-adapter name; retain `--prompt-file` for existing callers.
    '--prompt-file': 'promptFile', '--brief': 'promptFile', '--prompt': 'prompt', '--base': 'base',
    '--output-schema': 'outputSchema', '--thread-id': 'threadId',
    '-o': 'outFile', '--out': 'outFile',
    '--timeout': 'timeoutSec', '--reasoning-effort': 'reasoningEffort',
    '--usage-log': 'usageLog', '--label': 'label', '--attempt': 'attempt',
  };
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === '--search') {
      opts.search = true;
      continue;
    }
    const key = FLAGS[rest[i]];
    if (!key) continue; // ignore unknown flags — zero-dep, minimal parse
    const val = rest[++i];
    opts[key] = key === 'attempt'
      ? (Number.isInteger(Number(val)) && Number(val) > 0 ? Number(val) : null)
      : key === 'timeoutSec' ? Number(val) : val;
  }
  return opts;
}

if (require.main === module) {
  const opts = parseCliArgs(process.argv.slice(2));
  let result;
  try {
    result = run(opts);
  } catch (e) {
    result = shape({ ok: false, text: '', timedOut: false, exitCode: null, stderrTail: String((e && e.message) || e) });
  }
  if (result.ok && opts.outFile) {
    try {
      fs.mkdirSync(path.dirname(opts.outFile), { recursive: true });
      fs.writeFileSync(opts.outFile, result.text, 'utf8');
    } catch (e) {
      result = {
        ...result,
        ok: false,
        stderrTail: tail(`${result.stderrTail}\noutput file: ${e.message}`.trim(), STDERR_TAIL_LEN),
      };
    }
  }
  try {
    const logPath = usageLog ? usageLog.resolveUsageLog(opts.cwd || process.cwd(), opts.usageLog) : null;
    appendUsageLog(logPath, {
      id: `${opts.adapter || 'unknown'}:${result.sessionId || `${process.pid}:${Date.now()}`}:${opts.mode || 'unknown'}`,
      adapter: opts.adapter,
      mode: opts.mode,
      model: resolveModel(opts.adapter, opts.model) || 'default',
      label: opts.label,
      sessionId: result.sessionId,
      measured: !!result.usage,
      usage: result.usage,
      effort: opts.reasoningEffort || result.rollout?.effort || null,
      attempt: opts.attempt ?? null,
      quota: result.rollout?.quota ?? null,
      modelCalls: result.rollout?.modelCalls ?? null,
      peakContext: result.rollout?.peakContext ?? null,
      contextWindow: result.rollout?.contextWindow ?? null,
    });
  } catch (e) {
    result.stderrTail = tail(`${result.stderrTail}\nusage log: ${e.message}`.trim(), STDERR_TAIL_LEN);
  }
  const { rollout: _rollout, ...envelope } = result;
  process.stdout.write(JSON.stringify(envelope) + '\n');
  process.exit(result.ok ? 0 : 1);
}

